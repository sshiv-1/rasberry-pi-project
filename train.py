@torch.no_grad()
def extract_features(loader, split_name):
    feature_chunks, label_chunks = [], []
    started = time.time()
    total_batches = len(loader)

    model.eval()
    for batch_idx, (images, labels) in enumerate(loader, start=1):
        images = images.to(DEVICE, non_blocking=True)
        with torch.autocast(device_type=DEVICE.type, enabled=(DEVICE.type == "cuda")):
            features = model.features(images)
            features = F.adaptive_avg_pool2d(features, output_size=1).flatten(1)
        feature_chunks.append(features.float().cpu())
        label_chunks.append(labels.to(dtype=torch.long).cpu())

        if batch_idx % 25 == 0 or batch_idx == total_batches:
            elapsed = time.time() - started
            print(f"{split_name}: batch {batch_idx:>4}/{total_batches} | {elapsed:>6.1f}s")

    X = torch.cat(feature_chunks, dim=0).contiguous()
    y = torch.cat(label_chunks, dim=0).contiguous()
    return X, y

