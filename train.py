for epoch in range(1, EPOCHS + 1):
    epoch_started = time.time()
    head.train()
    permutation = torch.randperm(len(X_train))
    train_loss_sum = 0.0
    train_correct = 0
    train_seen = 0

    for start in range(0, len(X_train), TRAIN_BATCH):
        indices = permutation[start:start + TRAIN_BATCH]
        xb = X_train[indices].to(DEVICE, non_blocking=True)
        yb = y_train[indices].to(DEVICE, non_blocking=True)

        optimizer.zero_grad(set_to_none=True)
        logits = head(xb)
        loss = criterion(logits, yb)
        loss.backward()
        optimizer.step()
        scheduler.step()

        batch_n = len(indices)
        train_loss_sum += loss.item() * batch_n
        train_correct += (logits.argmax(dim=1) == yb).sum().item()
        train_seen += batch_n

    head.eval()
    valid_loss_sum = 0.0
    valid_correct = 0
    with torch.inference_mode():
        for start in range(0, len(X_valid), 2048):
            xb = X_valid[start:start + 2048].to(DEVICE, non_blocking=True)
            yb = y_valid[start:start + 2048].to(DEVICE, non_blocking=True)
            logits = head(xb)
            valid_loss_sum += F.cross_entropy(logits, yb, reduction="sum").item()
            valid_correct += (logits.argmax(dim=1) == yb).sum().item()

    train_loss = train_loss_sum / train_seen
    train_acc = train_correct / train_seen
    val_loss = valid_loss_sum / len(X_valid)
    val_acc = valid_correct / len(X_valid)
    lr_now = optimizer.param_groups[0]["lr"]
    epoch_seconds = time.time() - epoch_started

    history["epoch"].append(epoch)
    history["train_loss"].append(train_loss)
    history["train_acc"].append(train_acc)
    history["val_loss"].append(val_loss)
    history["val_acc"].append(val_acc)
    history["lr"].append(lr_now)
    history["seconds"].append(epoch_seconds)

    status = ""
    if val_acc > best_val_acc:
        best_val_acc = val_acc
        best_epoch = epoch
        torch.save(head.state_dict(), "best_head.pt")
        status = "BEST"

    print(f"{epoch:>3}/{EPOCHS} | {train_loss:>10.4f} | {train_acc:>8.2%} | {val_loss:>8.4f} | {val_acc:>6.2%} | {lr_now:>9.2e} | {epoch_seconds:>7.1f} | {status}")

