@torch.inference_mode()
def predict_cached_head(features, batch_size=2048):
    probabilities = []
    head.eval()
    for start in range(0, len(features), batch_size):
        xb = features[start:start + batch_size].to(DEVICE, non_blocking=True)
        probabilities.append(torch.softmax(head(xb), dim=1).cpu())
    return torch.cat(probabilities).numpy()

