def fallback_advice(class_name: str) -> dict:
    """
    Provide general fallback advice if the treatment JSON is missing
    an entry for the predicted class.
    """

    disease = (
        class_name.split("___", 1)[-1]
        .replace("_", " ")
        .casefold()
    )

    label = class_name.replace("___", " — ").replace("_", " ")

    if "healthy" in disease:
        advice = [
            "No disease was indicated among the model's training labels.",
            "Continue routine monitoring and appropriate watering; "
            "avoid unnecessary pesticides.",
        ]

    elif any(
        term in disease
        for term in ("virus", "huanglongbing", "greening")
    ):
        advice = [
            "Confirm the diagnosis first; established viral infections "
            "generally do not have a curative spray.",
            "Ask a local agricultural extension service about vector "
            "management and safe containment.",
        ]

    elif "mite" in disease:
        advice = [
            "Check leaf undersides to confirm mites. For small "
            "infestations, rinse foliage and protect beneficial insects.",
            "Use any crop-labeled pest control only after confirmation "
            "and according to its label.",
        ]

    else:
        advice = [
            "Treat this prediction as preliminary and confirm the cause "
            "before applying pesticides.",
            "Remove severely affected debris where practical, clean tools, "
            "improve airflow, and avoid prolonged leaf wetness.",
            "Ask a local agricultural extension service about "
            "crop-specific treatment options.",
        ]

    return {
        "label": label,
        "advice": advice,
        "note": (
            "General information only. Confirm the diagnosis and follow "
            "local agricultural guidance and product labels."
        ),
    }


# ============================================================
# IMAGE PREPROCESSING
# ============================================================

def preprocess(image: Image.Image) -> np.ndarray:
    """
    Match the ONNXDeploy class in train.py.

    1. Correct phone-photo orientation.
    2. Convert to RGB.
    3. Resize to IMG_SIZE x IMG_SIZE.
    4. Convert to float32.
    5. Change HWC to NCHW.
    6. Keep pixel values in [0, 255].

    DO NOT normalize or divide by 255 here.
    The ONNX graph already performs normalization.
    """

    transposed = ImageOps.exif_transpose(image)
    image = (transposed if transposed is not None else image).convert("RGB")

    resampling = getattr(
        Image,
        "Resampling",
        Image,
    ).BILINEAR

    image = image.resize(
        (IMG_SIZE, IMG_SIZE),
        resample=resampling,
    )

    array = np.asarray(image, dtype=np.float32)

    # HWC -> CHW -> NCHW
    array = np.transpose(array, (2, 0, 1))[None, ...]

    return np.ascontiguousarray(array, dtype=np.float32)


