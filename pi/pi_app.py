# PREDICTION
# ============================================================

def predict(image: Image.Image) -> list[dict]:
    """Run ONNX inference and return the top three predictions."""

    pixels = preprocess(image)

    output = session.run(
        [output_name],
        {input_name: pixels},
    )[0]

    if output.ndim != 2 or output.shape[0] != 1:
        raise RuntimeError(
            f"Unexpected model output shape {output.shape}; "
            "expected (1, classes)."
        )

    scores = np.asarray(output[0], dtype=np.float64)

    if scores.size != len(class_names):
        raise RuntimeError(
            f"Model returned {scores.size} scores but "
            f"class_names.json has {len(class_names)} labels."
        )

    if not np.all(np.isfinite(scores)):
        raise RuntimeError(
            "The model returned non-finite scores. Check model.onnx."
        )

    # train.py exports probabilities after softmax.
    # If a logits-only model is supplied, handle that too.
    score_sum = float(scores.sum())

    if not (
        np.all(scores >= 0.0)
        and np.all(scores <= 1.0)
        and abs(score_sum - 1.0) < 1e-3
    ):
        shifted = scores - np.max(scores)
        exp_scores = np.exp(shifted)
        scores = exp_scores / exp_scores.sum()

    top_indices = np.argsort(scores)[::-1][
        :min(3, len(class_names))
    ]

    results = []

    for index in top_indices:
        class_name = class_names[int(index)]

        results.append({
            "class_name": class_name,
            "label": (
                class_name
                .replace("___", " — ")
                .replace("_", " ")
            ),
            "confidence": float(scores[index]),
        })

    return results


def analyze_upload(upload) -> tuple[list[dict], dict, bool]:
    """Decode, validate, predict, and map advice for one uploaded image."""
    if not upload or not upload.filename:
        raise ValueError("Choose a leaf image first.")

    with Image.open(upload.stream) as opened:
        opened.verify()

    upload.stream.seek(0)
    with Image.open(upload.stream) as opened:
        if opened.width * opened.height > MAX_IMAGE_PIXELS:
            raise ValueError(
                "This image has too many decoded pixels. "
                "Please choose a smaller photo."
            )
        results = predict(opened)

    if not results:
        raise RuntimeError("The model did not return a prediction.")

    top_result = results[0]
    low_confidence = top_result["confidence"] < MIN_CONFIDENCE
    advice = treatment_advice.get(top_result["class_name"])
    used_fallback = not (
        isinstance(advice, dict)
        and isinstance(advice.get("advice"), list)
    )
    if used_fallback:
        logger.warning(
            "Using explicit general treatment fallback for class %s",
            top_result["class_name"],
        )
        advice = fallback_advice(top_result["class_name"])
    advice.setdefault(
        "note",
        "General guidance only. Confirm the diagnosis with a local "
        "agricultural expert.",
    )
    return results, advice, low_confidence


