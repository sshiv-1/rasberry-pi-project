def read_json(path: Path, fallback: Any = None) -> Any:
    """Load a JSON file and provide a useful error if it is malformed."""
    if not path.is_file():
        return fallback

    try:
        with path.open("r", encoding="utf-8-sig") as file:
            return json.load(file)

    except json.JSONDecodeError as exc:
        raise RuntimeError(
            f"{path.name} is not valid JSON "
            f"(line {exc.lineno}, column {exc.colno}). "
            "Regenerate it from train.py and copy it beside pi_app.py."
        ) from exc


def require_asset(path: Path, purpose: str) -> None:
    """Fail early if an essential deployment file is missing."""
    if not path.is_file():
        raise FileNotFoundError(
            f"Missing required file: {path.name}. "
            f"{purpose} Place it in the same folder as pi_app.py."
        )


require_asset(
    MODEL_PATH,
    "This is the trained model exported by train.py."
)

require_asset(
    CLASS_NAMES_PATH,
    "This maps the model output indices to disease labels."
)


# Metadata is optional.
metadata = read_json(METADATA_PATH, {}) or {}

if not isinstance(metadata, dict):
    logger.warning(
        "Ignoring %s because it is not a JSON object.",
        METADATA_PATH.name,
    )
    metadata = {}

try:
    IMG_SIZE = int(metadata.get("input_size", DEFAULT_IMAGE_SIZE))
except (TypeError, ValueError):
    IMG_SIZE = DEFAULT_IMAGE_SIZE

if IMG_SIZE < 32 or IMG_SIZE > 1024:
    raise RuntimeError(
        f"Invalid image size {IMG_SIZE} in deployment metadata."
    )


# Load class names.
class_names = read_json(CLASS_NAMES_PATH)

if (
    not isinstance(class_names, list)
    or not class_names
    or not all(isinstance(name, str) for name in class_names)
):
    raise RuntimeError(
        f"{CLASS_NAMES_PATH.name} must contain a JSON list "
        "of class-name strings, as generated by train.py."
    )

if len(set(class_names)) != len(class_names):
    raise RuntimeError(
        f"{CLASS_NAMES_PATH.name} contains duplicate class names."
    )


# Treatment advice is optional; fallback advice is available.
raw_treatment_advice = read_json(TREATMENT_PATH, {}) or {}

if not isinstance(raw_treatment_advice, dict):
    logger.warning(
        "Ignoring %s because its top-level JSON value is not an object.",
        TREATMENT_PATH.name,
    )
    raw_treatment_advice = {}

treatment_advice = raw_treatment_advice


# ============================================================
# INITIALIZE ONNX RUNTIME
# ============================================================

# Force CPU inference. PyTorch and TensorFlow are not needed on the Pi.
try:
    session_options = ort.SessionOptions()

    session_options.graph_optimization_level = (
        ort.GraphOptimizationLevel.ORT_ENABLE_ALL
    )

    session_options.intra_op_num_threads = max(
        1,
        min(4, os.cpu_count() or 1),
    )

    session = ort.InferenceSession(
        str(MODEL_PATH),
        sess_options=session_options,
        providers=["CPUExecutionProvider"],
    )

except Exception as exc:
    raise RuntimeError(
        "ONNX Runtime could not load model.onnx. Confirm this is the "
        "model exported by train.py and that ONNX Runtime is installed "
        "for your Raspberry Pi's OS and architecture. "
        f"Original error: {exc}"
    ) from exc


inputs = session.get_inputs()
outputs = session.get_outputs()

if not inputs or not outputs:
    raise RuntimeError(
        "model.onnx has no readable input or output tensors."
    )

input_meta = inputs[0]
output_meta = outputs[0]

input_name = input_meta.name
output_name = output_meta.name
input_shape = input_meta.shape


# train.py exports:
# Input: NCHW float32 RGB pixels in the range [0, 255].
# Shape: [batch_size, 3, 160, 160].
# Normalization and softmax are already inside the ONNX model.

if len(input_shape) != 4:
    raise RuntimeError(
        f"Expected a 4-D NCHW ONNX input, got shape {input_shape}."
    )

if isinstance(input_shape[1], int) and input_shape[1] != 3:
    raise RuntimeError(
        f"Expected 3 RGB channels in model.onnx, got shape {input_shape}."
    )

for axis in (2, 3):
    if (
        isinstance(input_shape[axis], int)
        and input_shape[axis] != IMG_SIZE
    ):
        raise RuntimeError(
            f"Model expects image shape {input_shape}; configured image "
            f"size is {IMG_SIZE}. Use the deployment_metadata.json "
            "generated alongside this model, or set PLANT_IMAGE_SIZE "
            "to the exported size."
        )

if (
    isinstance(output_meta.shape[-1], int)
    and output_meta.shape[-1] != len(class_names)
):
    raise RuntimeError(
        f"Model outputs {output_meta.shape[-1]} classes but "
        f"{CLASS_NAMES_PATH.name} contains {len(class_names)}. "
        "These files must come from the same train.py run."
    )

if metadata.get("classes") not in (None, len(class_names)):
    raise RuntimeError(
        f"deployment_metadata.json says {metadata.get('classes')} "
        f"classes but class_names.json contains {len(class_names)}. "
        "Copy matching deployment files from one training run."
    )


logger.info("Loaded ONNX model: %s", MODEL_PATH.name)
logger.info(
    "Classes: %d | input image: %dx%d | provider: CPUExecutionProvider",
    len(class_names),
    IMG_SIZE,
    IMG_SIZE,
)
logger.info(
    "Treatment advice entries loaded: %d",
    len(treatment_advice),
)


